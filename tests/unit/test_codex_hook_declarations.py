def test_a_session_seen_by_both_sources_is_yielded_once_with_both_files(tmp_path: Path) -> None:
    home = tmp_path / "codex-home"
    work = _workspace(tmp_path)
    _rehome_rollout(home, work)
    _plant_declaration(home, work)

    discovered = list(CodexRolloutSessionSource(home=home).discover())
    assert [one.cli_session_id for one in discovered] == [SESSION_WITH_WRITES]
    session = discovered[0]
    assert session.files is not None
    assert set(session.files) == {work / ROLLOUT_WRITTEN_REL, work / DECLARED_REL}
    assert session.notes["hook_declared_writes"] == 1
    assert session.notes["attributed_writes"] == 1


def test_a_declaration_with_no_rollout_in_the_window_is_still_a_listed_session(tmp_path: Path) -> None:
    """The rollout scan is bounded and Codex archives old sessions. A turn's
    write record carries its own identity and cwd, so it needs no rollout."""
    home = tmp_path / "codex-home"
    work = _workspace(tmp_path)
    _plant_declaration(home, work, session_id="019ffffe-0000-7000-8000-00000000cs34")

    discovered = list(CodexRolloutSessionSource(home=home).discover())
    assert [one.cli_session_id for one in discovered] == ["019ffffe-0000-7000-8000-00000000cs34"]
    assert discovered[0].files == (work / DECLARED_REL,)
    assert discovered[0].root == work


def test_a_differently_named_plugin_install_is_still_read(tmp_path: Path) -> None:
    home = tmp_path / "codex-home"
    work = _workspace(tmp_path)
    _plant_declaration(home, work, session_id="019ffffe-0000-7000-8000-0000000alt01", plugin_id="matrx-codex-plugin")
    assert [one.cli_session_id for one in CodexRolloutSessionSource(home=home).discover()] == [
        "019ffffe-0000-7000-8000-0000000alt01"
    ]


def test_silence_from_the_hook_source_is_reported_as_its_own_fact(tmp_path: Path) -> None:
    """An absent plugin is a DIFFERENT fact from a plugin that ran and found
    nothing, and before this the screen could only talk about apply_patch —
    true, and useless to the person looking at an empty panel."""
    home = tmp_path / "codex-home"
    (home / "sessions").mkdir(parents=True)
    source = CodexRolloutSessionSource(home=home)
    list(source.discover())
    sentences = source.describe_gaps({})
    assert any("hook-time write record yet" in sentence for sentence in sentences)
    assert any("AI Matrx plugin for Codex" in sentence for sentence in sentences)

    _plant_declaration(home, _workspace(tmp_path))
    list(source.discover())
    after = source.describe_gaps({})
    assert any("have a hook-time write record naming 1 file(s)" in sentence for sentence in after)
    assert not any("hook-time write record yet" in sentence for sentence in after)
    # The producer's repository refusal reaches the person as a sentence.
    assert any(
        "inside a git checkout and are deliberately not captured" in sentence for sentence in after
    )


# --------------------------------------------------------------------------
# End to end: the lane captures it, with the repository rule intact
# --------------------------------------------------------------------------


async def test_the_lane_captures_a_hook_declared_file_and_still_refuses_a_checkout(tmp_path: Path) -> None:
    home = tmp_path / "codex-home"
    work = _workspace(tmp_path)
    # A second declared path that lives inside a checkout. The producer would
    # never have declared it; the lane must refuse it anyway, because an
    # explicit file list is not a second door into the upload with the rule
    # switched off.
    checkout = work / "vendored-repo"
    (checkout / ".git").mkdir(parents=True)
    source_file = checkout / "main.py"
    source_file.write_text("SECRET = 'never uploaded'\n")
    path = _plant_declaration(home, work)
    record = json.loads(path.read_text())
    record["files"][str(source_file)] = {"path": str(source_file), "change": "created", "size": 26}
    path.write_text(json.dumps(record))

    durable = tmp_path / "durable"
    db = LocalDatabase(tmp_path / "codex.db")
    await db.connect()
    lane = CodingSessionArtifactsLane(
        db=db,
        provider="codex",
        source=CodexRolloutSessionSource(home=home),
        durable_root=durable,
        files_client=_FakeFilesClient(),  # type: ignore[arg-type]
        cloud_enabled=False,
    )
    try:
        tick = await lane.run_once()
    finally:
        await db.close()
    assert tick["captured"] >= 1

    session_dir = durable / SESSION_WITH_WRITES
    kept = sorted(
        p.relative_to(session_dir).as_posix()
        for p in session_dir.rglob("*")
        if p.is_file() and p.name != MANIFEST_NAME
    )
    assert kept == [DECLARED_REL]
    manifest = json.loads((session_dir / MANIFEST_NAME).read_text())
    assert "never uploaded" not in json.dumps(manifest)
    assert "main.py" not in json.dumps(manifest)
